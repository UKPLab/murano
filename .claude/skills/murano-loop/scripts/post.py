"""Lint and post every text the agent loop puts on GitHub.

Agents never call `gh pr edit --body*`, `gh issue edit --body*`,
`gh pr comment` or `gh issue comment` directly; they go through `post`, which
refuses text that breaks the rules below. A human reads each text first, so
what they need sits on top and the agent-facing detail goes in a collapsed
`<details>` block.

    post.py check KIND FILE
    post.py post KIND NUMBER FILE [--edit COMMENT_ID]

KIND is one of:
    body      PR body                      (gh pr edit NUMBER)
    issue     method proposal issue body   (gh issue edit NUMBER)
    dossier   sourcing dossier comment     (comment on the issue)
    review    review verdict comment       (comment on the PR)
    reply     revise reply comment         (comment on the PR)
    question  open-question comment        (comment on the issue or PR)
    log       tick log comment             (comment on the log issue)
--edit rewrites an existing comment in place instead of adding one.
"""

import re
import subprocess
import sys
from pathlib import Path

DISCLAIMER = "> *Generated by the murano agent loop.*"
LIMITS = {
    "question": 40,  # one open question
    "questions": 3,
    "code_spans": 6,  # inline code a human reads: more reads as a diff dump
    "difference": 25,  # one "Differences from the reference code" bullet
    "reply_line": 20,
    "finding": 45,
    "review_lead": 50,  # the lines between VERDICT and the first finding heading
    "question_comment": 80,
    "log": 150,
}
# Per kind: words above <details>, words in the opening, words inside <details>,
# and the headings allowed above <details> (a regex).
VISIBLE = {
    "body": (150, 60, None, r"Open questions"),
    "dossier": (120, 70, 600, r"Dossier: .*|Open questions"),
    "issue": (120, 120, 200, r"Paper|Method|Murano mapping"),
}
DASHES = re.compile("[–—]| -- ")


def words(text):
    return len(re.findall(r"\S+", text))


def strip_comments(text):
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def bullets(section):
    """Top-level list items, with their wrapped continuation lines joined."""
    items = []
    for line in section.splitlines():
        if re.match(r"\s*(?:[-*]|\d+\.)\s", line) and not line.startswith("  "):
            items.append(line)
        elif items and line.strip() and not line.startswith("#"):
            items[-1] += " " + line.strip()
    return items


def sections(text):
    """Map each heading to the text under it ('' holds the text before)."""
    out, key = {"": ""}, ""
    for line in text.splitlines():
        m = re.match(r"#{2,4}\s+(.*)", line)
        if m:
            key = m.group(1).strip()
            out[key] = ""
        else:
            out[key] += line + "\n"
    return out


def check_questions(qs):
    errs = []
    if not qs.strip():
        return ["'### Open questions' is missing or empty (write 'None.')"]
    if qs.strip() == "None.":
        return []
    items = bullets(qs)
    if len(items) > LIMITS["questions"]:
        errs.append(
            f"{len(items)} open questions, limit {LIMITS['questions']}: keep only what a human must decide"
        )
    for q in items:
        if "Provisional:" not in q:
            errs.append(f"open question without 'Provisional:': {q[:60]}")
        if (n := words(q)) > LIMITS["question"]:
            errs.append(
                f"open question is {n} words, limit {LIMITS['question']}: {q[:60]}"
            )
    return errs


def check_layered(text, kind):
    """A short human part above <details>, the agent brief inside it."""
    top, lead, inner, headings = VISIBLE[kind]
    errs = []
    if "<details>" not in text:
        return errs + ["missing the collapsed <details> block for the detail"]
    head, hidden = text.split("<details>", 1)
    visible = strip_comments(head).replace(DISCLAIMER, "")
    visible = re.sub(r"^Closes #\d+.*$", "", visible, flags=re.M)
    parts = sections(visible)
    extra = [h for h in parts if h and not re.fullmatch(headings, h)]
    if extra:
        errs.append(f"move {extra} inside <details>")
    if (n := words(visible)) > top:
        errs.append(
            f"{n} words above <details>, limit {top}: drop points, don't compress"
        )
    if (n := words(parts[""])) > lead:
        errs.append(f"opening is {n} words, limit {lead}")
    if (n := len(re.findall(r"`[^`]+`", visible))) > LIMITS["code_spans"]:
        errs.append(
            f"{n} code spans above <details>, limit {LIMITS['code_spans']}: say it in words"
        )
    if DASHES.search(visible):
        errs.append("em/en dash above <details>")
    if "Open questions" in headings:
        errs += check_questions(parts.get("Open questions", ""))
    if inner and (n := words(strip_comments(hidden))) > inner:
        errs.append(
            f"{n} words inside <details>, limit {inner}: cut what the code or paper already says"
        )
    return errs


def check_body(text):
    errs = check_layered(text, "body")
    if not re.search(r"^Closes #\d+", text, re.M):
        errs.append("missing 'Closes #<issue>'")
    if not re.search(r"<!-- agent-review-round: \d+ -->", text):
        errs.append("missing '<!-- agent-review-round: N -->'")
    hidden = sections(text.split("<details>", 1)[-1])
    for d in bullets(hidden.get("Differences from the reference code", "")):
        if (n := words(d)) > LIMITS["difference"]:
            errs.append(
                f"difference is {n} words, limit {LIMITS['difference']}: {d[:60]}"
            )
    return errs


def check_dossier(text):
    errs = check_layered(text, "dossier")
    if "<!-- murano-dossier -->" not in text:
        errs.append("missing '<!-- murano-dossier -->'")
    return errs


def check_issue(text):
    return check_layered(text, "issue")


def check_reply(text):
    errs = []
    sha = r"`?[0-9a-f]{7,40}`?"
    for line in text.replace(DISCLAIMER, "").strip().splitlines():
        if not line.strip():
            continue
        if not re.match(
            rf"\d+\. (Fixed in {sha}(,? (and )?{sha})*|Not changed): ", line
        ):
            errs.append(
                f"only '<n>. Fixed in <sha>: ...' or '<n>. Not changed: ...' lines: {line[:60]}"
            )
        elif (n := words(line)) > LIMITS["reply_line"]:
            errs.append(f"line is {n} words, limit {LIMITS['reply_line']}: {line[:60]}")
    return errs


def check_review(text):
    errs = []
    if "<!-- murano-review -->" not in text:
        errs.append("missing '<!-- murano-review -->'")
    m = re.search(r"^VERDICT: (CHANGES_REQUESTED|READY_TO_MERGE)\s*$", text, re.M)
    if not m:
        errs.append("missing 'VERDICT: CHANGES_REQUESTED|READY_TO_MERGE'")
    else:
        lead = re.split(r"^###", text[m.end() :], maxsplit=1, flags=re.M)[0]
        if (n := words(lead)) > LIMITS["review_lead"]:
            errs.append(
                f"text under VERDICT is {n} words, limit {LIMITS['review_lead']}"
            )
    for f in bullets(sections(text).get("Must fix", "")):
        if (n := words(f)) > LIMITS["finding"]:
            errs.append(f"finding is {n} words, limit {LIMITS['finding']}: {f[:60]}")
    if DASHES.search(text):
        errs.append("em/en dash")
    return errs


def check_question(text):
    errs = []
    if "<!-- murano-open-question -->" not in text:
        errs.append("missing '<!-- murano-open-question -->'")
    if "Provisional:" not in text:
        errs.append("missing 'Provisional: <choice>, because <why>.'")
    if (n := words(strip_comments(text))) > LIMITS["question_comment"]:
        errs.append(f"{n} words, limit {LIMITS['question_comment']}")
    return errs


def check_log(text):
    if (n := words(strip_comments(text))) > LIMITS["log"]:
        return [f"{n} words, limit {LIMITS['log']}: one line per action"]
    return []


CHECKS = {
    "body": check_body,
    "issue": check_issue,
    "dossier": check_dossier,
    "review": check_review,
    "reply": check_reply,
    "question": check_question,
    "log": check_log,
}


def check(kind, text):
    errs = (
        []
        if text.lstrip().startswith(DISCLAIMER)
        else [f"start with the line {DISCLAIMER!r}"]
    )
    return errs + CHECKS[kind](text)


def require(kind, path):
    """Exit with the errors when the text at ``path`` breaks the rules."""
    errs = check(kind, Path(path).read_text())
    for e in errs:
        print(f"{kind}: {e}", file=sys.stderr)
    if errs:
        sys.exit(1)


def main(argv):
    if len(argv) < 3 or argv[0] not in ("check", "post") or argv[1] not in CHECKS:
        sys.exit(__doc__)
    cmd, kind, *rest = argv
    edit = None
    if "--edit" in rest:
        i = rest.index("--edit")
        edit = rest[i + 1]
        del rest[i : i + 2]
    path = rest[-1]
    require(kind, path)
    if cmd == "check":
        print("ok")
        return
    number = rest[0]
    if kind == "body":
        gh = ["gh", "pr", "edit", number, "--body-file", path]
    elif kind == "issue":
        gh = ["gh", "issue", "edit", number, "--body-file", path]
    elif edit:
        gh = [
            "gh",
            "api",
            "-X",
            "PATCH",
            f"repos/{{owner}}/{{repo}}/issues/comments/{edit}",
            "-F",
            f"body=@{path}",
            "--jq",
            ".html_url",
        ]
    else:
        gh = ["gh", "issue", "comment", number, "--body-file", path]
    subprocess.run(gh, check=True)


if __name__ == "__main__":
    main(sys.argv[1:])
